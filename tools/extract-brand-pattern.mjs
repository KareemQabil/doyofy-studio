// Extracts the official Doyofy brand-pattern motifs from design-source/brand/ASSETS/PATTERN/Doyofy Color Patterns.svg
// (owner-supplied identity pack) into src/features/signature/brand-pattern.generated.ts as normalised path groups.
// Shapes are used exactly as supplied — only translated to the origin and recoloured via currentColor.
import fs from 'node:fs';
import path from 'node:path';
import { need, chromiumPath, ROOT } from './lib.mjs';
const { chromium } = need('playwright');
const svg = fs.readFileSync(path.join(ROOT, 'design-source/brand/ASSETS/PATTERN [PNG+SVG]/Doyofy Color Patterns.svg'), 'utf8');
const b = await chromium.launch({ executablePath: chromiumPath() });
const p = await b.newPage();
await p.setContent(`<body>${svg}</body>`);
const groups = await p.evaluate(() => {
  const top = [...document.querySelector('svg > g').children].filter((c) => c.tagName === 'g');
  return top.map((g) => {
    const bb = g.getBBox();
    const paths = [...g.querySelectorAll('path')].map((el) => {
      // bake each path's ancestor transforms into its coordinates relative to the group origin
      const m = el.getCTM(); const gm = g.getCTM().inverse();
      const rel = gm.multiply(m);
      return { d: el.getAttribute('d'), t: [rel.a, rel.b, rel.c, rel.d, rel.e - bb.x, rel.f - bb.y].map((v) => +v.toFixed(3)) };
    });
    return { x: bb.x, y: bb.y, w: +bb.width.toFixed(2), h: +bb.height.toFixed(2), paths };
  });
});
await b.close();
// pick: motif "bloom" (2x2 mirrored), motif "knot" (rotated), motif "column" (vertical chain), tile "grid" cell, tile "band" cell, tile "weave" column
const find = (fx, fy) => groups.find((g) => Math.abs(g.x - fx) < 3 && Math.abs(g.y - fy) < 3);
const pick = {
  bloom: find(97, -2323), knot: find(67, -971), column: find(77, 153),
  gridCell: find(-1745, -2515), bandCell: find(-1753, -914), weave: find(-1739, 153),
};
const toSym = (g) => ({ w: g.w, h: g.h, paths: g.paths.map((q) => (q.t.join(',') === '1,0,0,1,0,0' ? { d: q.d } : q)) });
const out = Object.fromEntries(Object.entries(pick).map(([k, g]) => { if (!g) throw new Error('missing ' + k); return [k, toSym(g)]; }));
// grid period from the field: neighbouring cells
const gridStep = { x: +(find(-1390, -2515).x - find(-1745, -2515).x).toFixed(2), y: +(find(-1745, -2022).y - find(-1745, -2515).y).toFixed(2) };
const bandStep = +(find(-1379, -914).x - find(-1753, -914).x).toFixed(2);
fs.writeFileSync(path.join(ROOT, 'src/features/signature/brand-pattern.generated.ts'),
`/* AUTO-GENERATED by tools/extract-brand-pattern.mjs from the owner-supplied Doyofy identity pack
 * (design-source/brand/ASSETS/PATTERN [PNG+SVG]/Doyofy Color Patterns.svg). Do not edit by hand. */
export interface PatternPath { d: string; t?: number[] }
export interface PatternSymbol { w: number; h: number; paths: PatternPath[] }
export const BRAND_PATTERN: Record<'bloom' | 'knot' | 'column' | 'gridCell' | 'bandCell' | 'weave', PatternSymbol> = ${JSON.stringify(out)};
export const GRID_STEP = ${JSON.stringify(gridStep)};
export const BAND_STEP = ${bandStep};
`);
console.log('ok', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, [v.w, v.h, v.paths.length]])), gridStep, bandStep);
// static tiles for CSS backgrounds (public/assets/brand/): the grid cell on its own period, per brand colour
const dir = path.join(ROOT, 'public/assets/brand'); fs.mkdirSync(dir, { recursive: true });
const body = (s) => s.paths.map((q) => `<path d="${q.d}"${q.t && q.t.join(',') !== '1,0,0,1,0,0' ? ` transform="matrix(${q.t.join(' ')})"` : ''}/>`).join('');
for (const [name, color] of Object.entries({ gold: '#C7A661', ivory: '#F2EAD9', beige: '#E4D5B4', charcoal: '#262626', red: '#BC4749', turquoise: '#2EB7B7' })) {
  fs.writeFileSync(path.join(dir, `pattern-grid-${name}.svg`), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${gridStep.x} ${gridStep.y}" fill="${color}">${body(out.gridCell)}</svg>`);
}
for (const k of ['bloom', 'knot', 'column']) fs.writeFileSync(path.join(dir, `motif-${k}.svg`), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${out[k].w} ${out[k].h}" fill="#C7A661">${body(out[k])}</svg>`);
console.log('tiles written');
