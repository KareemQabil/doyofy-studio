#!/usr/bin/env node
/**
 * npm run port:canon
 *
 * Converts the canonical Design-canvas components (canonical/CardFace.dc.html, canonical/Scene.dc.html)
 * into plain ES modules the production engine renders WITHOUT the canvas runtime:
 *
 *   src/cards/canon/generated.js   — shared <defs> + one template function per card design (10)
 *   src/scenes/css/generated.js    — shared <defs> + one template function per CSS/SVG scene (10)
 *
 * The conversion is mechanical so the markup stays byte-for-byte traceable to the original:
 *   {{a.b}}                         → ${e(v.a.b)}            (HTML-escaped)
 *   <sc-if value="{{x}}">…</sc-if>   → ${v.x ? `…` : ''}
 *   <sc-for list="{{xs}}" as="i">…  → ${v.xs.map((i) => `…`).join('')}
 * Scene parallax holes ({{pf}}, {{pm}}, {{pn}}) become CSS variables (var(--pf) …) so pointer
 * movement updates three custom properties instead of re-rendering the scene.
 * Each output records the sha256 of the source file it was generated from.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { ROOT } from './lib.mjs';

const read = (f) => fs.readFileSync(path.join(ROOT, 'canonical', f), 'utf8');
const sha = (s) => crypto.createHash('sha256').update(s).digest('hex');

function xdc(src) {
  const a = src.indexOf('<x-dc>'), b = src.lastIndexOf('</x-dc>');
  return src.slice(a + 6, b).replace(/<helmet>[\s\S]*?<\/helmet>/, '').trim();
}

/** find the matching close tag for the open tag at index i (handles nesting of the same tag) */
function matchClose(s, i, tag) {
  const open = new RegExp(`<${tag}[\\s>]`, 'g'), close = `</${tag}>`;
  let depth = 0, j = i;
  while (j < s.length) {
    open.lastIndex = j;
    const mo = open.exec(s);
    const mc = s.indexOf(close, j);
    if (mo && mo.index < mc) { depth++; j = mo.index + 1; continue; }
    depth--; if (depth === 0) return mc; j = mc + 1;
  }
  throw new Error('unclosed ' + tag);
}

function convert(s, loopVars = [], root = 'v', holeMap = {}) {
  let out = '';
  let i = 0;
  while (i < s.length) {
    const nextIf = s.indexOf('<sc-if', i), nextFor = s.indexOf('<sc-for', i);
    const cands = [nextIf, nextFor].filter((x) => x >= 0);
    const n = cands.length ? Math.min(...cands) : -1;
    if (n < 0) { out += holes(s.slice(i), loopVars, root, holeMap); break; }
    out += holes(s.slice(i, n), loopVars, root, holeMap);
    const tag = n === nextIf ? 'sc-if' : 'sc-for';
    const headEnd = s.indexOf('>', n);
    const head = s.slice(n, headEnd + 1);
    const close = matchClose(s, n, tag);
    const body = s.slice(headEnd + 1, close);
    if (tag === 'sc-if') {
      const cond = ref(head.match(/value="\{\{\s*([^}]+?)\s*\}\}"/)[1], loopVars, root);
      out += '${' + cond + ' ? `' + convert(body, loopVars, root, holeMap) + "` : ''}";
    } else {
      const list = ref(head.match(/list="\{\{\s*([^}]+?)\s*\}\}"/)[1], loopVars, root);
      const as = head.match(/as="([^"]+)"/)[1];
      out += '${(' + list + ').map((' + as + ', $index) => `' + convert(body, [...loopVars, as, '$index'], root, holeMap) + "`).join('')}";
    }
    i = close + tag.length + 3;
  }
  return out;
}

function ref(p, loopVars, root) {
  const head = p.split('.')[0];
  if (/^(true|false|-?\d+(\.\d+)?)$/.test(p)) return p;
  return loopVars.includes(head) ? p : `${root}.${p}`;
}

function holes(s, loopVars, root, holeMap) {
  return s.replace(/`/g, '\\`').replace(/\$\{/g, '\\${').replace(/\{\{\s*([^}]+?)\s*\}\}/g, (m, p) => {
    if (holeMap[p]) return holeMap[p];
    return '${e(' + ref(p, loopVars, root) + ')}';
  });
}

/** split a component root into  [defsSvg, {key: blockMarkup}]  using the top-level sc-if value="{{is.key}}" blocks */
function splitBlocks(inner) {
  const blocks = {};
  const re = /<sc-if value="\{\{is\.([a-z]+)\}\}"[^>]*>/g;
  let m;
  while ((m = re.exec(inner))) {
    const close = matchClose(inner, m.index, 'sc-if');
    blocks[m[1]] = inner.slice(m.index + m[0].length, close).trim();
    re.lastIndex = close;
  }
  const defs = inner.match(/<svg width="0" height="0"[\s\S]*?<\/svg>/)[0];
  return { defs, blocks };
}

function rootAttrs(inner) { return inner.match(/^<div ([^>]*)>/)[1]; }

const header = (file, src) => `/* GENERATED by tools/port-canon.mjs from canonical/${file}
 * source sha256 ${sha(src)}
 * Do not edit by hand — change the canonical source (or the generator) and run \`npm run port:canon\`. */
/* eslint-disable */
const e = (v) => String(v ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
`;

// ---------------------------------------------------------------- CardFace
{
  const src = read('CardFace.dc.html');
  const inner = xdc(src);
  let { defs, blocks } = splitBlocks(inner);
  // the canonical source gives a gradient and a <g> the same id (cf-cheart); a duplicate id resolves to the
  // first match, so <use href="#cf-cheart"> could hit the gradient. Give the gradient its own id.
  defs = defs.replace('<radialGradient id="cf-cheart"', '<radialGradient id="cf-cheart-g"').replace('fill="url(#cf-cheart)"', 'fill="url(#cf-cheart-g)"');
  let js = header('CardFace.dc.html', src);
  js += `\n/** shared SVG <defs> (ids cf-*) — mounted once per document */\nexport const CARD_DEFS = \`${holes(defs.replace('<svg width="0" height="0"', '<svg class="cf-defs" width="0" height="0"'), [], 'v', {})}\`;\n`;
  js += `\n/** root element attributes of the 300×420 face, as in the canonical CardFace */\nexport const CARD_ROOT = ${JSON.stringify(rootAttrs(inner))};\n`;
  js += `\n/** v = { c: content, stars: [...] } — see cards/canon/vals.js */\nexport const CARD_FACES = {\n`;
  for (const [k, b] of Object.entries(blocks)) js += `  ${k}: (v) => \`${convert(b)}\`,\n`;
  js += '};\n';
  fs.mkdirSync(path.join(ROOT, 'src/cards/canon'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'src/cards/canon/generated.js'), js);
  console.log('[port] cards:', Object.keys(blocks).join(', '));
}

// ---------------------------------------------------------------- Scene
{
  const src = read('Scene.dc.html');
  const inner = xdc(src);
  const { defs, blocks } = splitBlocks(inner);
  const holeMap = { pf: 'var(--pf, none)', pm: 'var(--pm, none)', pn: 'var(--pn, none)' };
  let js = header('Scene.dc.html', src);
  js += `\nexport const SCENE_DEFS = \`${holes(defs.replace('<svg width="0" height="0"', '<svg class="sc-defs" width="0" height="0"'), [], 'v', {})}\`;\n`;
  js += `\nexport const SCENE_ROOT = ${JSON.stringify(rootAttrs(inner))};\n`;
  js += `\n/** v = seeded particle lists from scenes/css/vals.js; parallax via --pf/--pm/--pn on the scene root */\nexport const SCENES = {\n`;
  for (const [k, b] of Object.entries(blocks)) js += `  ${k}: (v) => \`${convert(b, [], 'v', holeMap)}\`,\n`;
  js += '};\n';
  fs.mkdirSync(path.join(ROOT, 'src/scenes/css'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'src/scenes/css/generated.js'), js);
  console.log('[port] scenes:', Object.keys(blocks).join(', '));
}

// ---------------------------------------------------------------- motion.css (canonical motion language)
{
  const src = read('motion.css');
  fs.mkdirSync(path.join(ROOT, 'src/styles'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'src/styles/canon-motion.css'), `/* GENERATED copy of canonical/motion.css (sha256 ${sha(src)}) — the canonical motion language.\n   Production overrides live in studio.css; do not edit this file. */\n` + src);
  console.log('[port] motion.css copied');
}
