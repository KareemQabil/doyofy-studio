// Imports the chosen vector motifs of the Doyofy Designer Kit into src/cards/kit-art.ts.
//   node tools/import-card-kit.mjs <kit-folder>
// Each motif is inlined (no extra requests), cropped to its artwork bounds, and cleaned:
// no metadata, no ids, no gradients (a url(#…) fill becomes its mid colour), so many cards can share a page.
// `mono` motifs turn every non-white colour into currentColor, so a card tints them with its own palette.
// The raster layers (WebP in public/assets/cards/kit/) are converted separately; see public/assets/cards/kit/PROVENANCE.json.
import fs from 'node:fs';
import path from 'node:path';

const kit = process.argv[2];
if (!kit || !fs.existsSync(path.join(kit, 'elements'))) { console.error('usage: node tools/import-card-kit.mjs <kit-folder>'); process.exit(1); }

// key, kit id, crop [x0, y0, x1, y1] in the motif's 1000×1000 space (measured artwork bounds + a small margin), mono
const PICK = [
  ['archFrame', 'DYO_FRAMES_001', [146, 67, 854, 922], true],
  ['ovalFrame', 'DYO_FRAMES_002', [120, 25, 880, 960], true],
  ['squareFrame', 'DYO_FRAMES_003', [87, 78, 930, 922], true],
  ['corners', 'DYO_FRAMES_004', [61, 75, 922, 939], false],
  ['divider', 'DYO_FRAMES_005', [87, 443, 913, 530], true],
  ['tile', 'DYO_GEOMETRIC_001', [0, 0, 1000, 1000], true],
  ['rosette', 'DYO_GEOMETRIC_002', [128, 120, 872, 866], true],
  ['quatrefoil', 'DYO_GEOMETRIC_004', [0, 0, 1000, 1000], true],
  ['star8', 'DYO_GEOMETRIC_010', [84, 84, 898, 901], true],
  ['rings', 'DYO_WEDDING_003', [170, 187, 839, 810], false],
  ['balloons', 'DYO_BIRTHDAY_005', [128, 117, 822, 922], false],
  ['bunting', 'DYO_BIRTHDAY_002', [34, 240, 948, 633], false],
  ['cake', 'DYO_BIRTHDAY_003', [122, 184, 892, 860], false],
  ['gradCap', 'DYO_GRADUATION_001', [96, 175, 904, 869], false],
  ['laurel', 'DYO_GRADUATION_002', [146, 20, 851, 957], true],
  ['cloud', 'DYO_NEWBORN_001', [75, 296, 913, 783], false],
  ['moonCloud', 'DYO_NEWBORN_002', [161, 164, 845, 966], false],
  ['footprints', 'DYO_NEWBORN_003', [172, 222, 819, 751], false],
  ['crescent', 'DYO_RAMADAN_003', [78, 137, 857, 883], true],
  ['lanterns', 'DYO_RAMADAN_004', [175, 205, 816, 683], false],
  ['dallah', 'DYO_RAMADAN_005', [122, 55, 875, 951], false],
  ['jasmine', 'DYO_BOTANICAL_001', [222, 52, 801, 922], false],
  ['petals', 'DYO_BOTANICAL_006', [52, 228, 916, 948], false],
  ['olive', 'DYO_BOTANICAL_015', [249, 125, 786, 919], false],
];

const files = fs.readdirSync(path.join(kit, 'elements'), { recursive: true }).map(String);
const GRADIENT_MID = { metal: '#c9a865', silk: '#c2827f', glow: '#f3dfa6', foil: '#d8b66c', liner: '#e8dcc4' };
const out = {};
let bytes = 0;
for (const [key, id, [x0, y0, x1, y1], mono] of PICK) {
  const rel = files.find((f) => path.basename(f).startsWith(`${id}_`) && f.endsWith('.svg'));
  if (!rel) throw new Error(`missing ${id}`);
  const src = fs.readFileSync(path.join(kit, 'elements', rel), 'utf8');
  let body = src.match(/<g id="artwork">([\s\S]*)<\/g>\s*<\/svg>\s*$/)?.[1];
  if (body == null) throw new Error(`no artwork group in ${id}`);
  body = body.replace(/url\(#([a-z-]+)\)/g, (_, g) => GRADIENT_MID[g] ?? '#c9a865')
    .replace(/\s+id="[^"]*"/g, '').replace(/(\d+\.\d)\d+/g, '$1').replace(/\.0(?=\D)/g, '').replace(/>\s+</g, '><').replace(/\s{2,}/g, ' ');
  if (mono) body = body.replace(/(fill|stroke)="(#[0-9a-fA-F]{3,6})"/g, (m, attr, c) => (/^#f{3}(f{3})?$/i.test(c) ? m : `${attr}="currentColor"`));
  if (/url\(#|\bid=/.test(body)) throw new Error(`unclean ${id}`);
  out[key] = { id, vb: `${x0} ${y0} ${x1 - x0} ${y1 - y0}`, svg: body };
  bytes += body.length;
}

const ts = `// Generated by tools/import-card-kit.mjs from the Doyofy Designer Kit (original code-native vectors). Do not edit by hand.
// Each motif: kit id, crop viewBox, and clean inner markup (no ids, no gradients). Mono motifs draw in currentColor.
export interface KitMotif { id: string; vb: string; svg: string }
export const KIT: Record<string, KitMotif> = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync(path.join('src', 'cards', 'kit-art.ts'), ts);
console.log(`kit-art.ts: ${PICK.length} motifs, ${(bytes / 1024).toFixed(1)} KB of markup`);
